export function icon(name, size = 16) {
  const span = document.createElement('span');
  span.className = 'fl-icon fl-icon-' + name;
  span.setAttribute('aria-hidden', 'true');
  span.innerHTML = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${PATHS[name] || ''}</svg>`;
  return span;
}

/** Nombre à la française avec espace fine insécable : 1 024. */
export function fmtInt(n) {
  return new Intl.NumberFormat('fr-FR').format(n);
}

/** « 1 ligne », « 12 lignes ». */
export function plural(n, one, many) {
  return `${fmtInt(n)} ${n > 1 ? many : one}`;
}

/** Appelle `fn` après `ms` sans nouvel appel. */
export function debounce(fn, ms) {
  let t = null;
  const d = (...args) => { clearTimeout(t); t = setTimeout(() => fn(...args), ms); };
  d.flush = (...args) => { clearTimeout(t); fn(...args); };
  d.cancel = () => clearTimeout(t);
  return d;
}
